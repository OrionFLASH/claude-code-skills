#!/usr/bin/env python3
"""Browser window of the run: visible (headed) or hidden, and slow-mo — one place for the whole run.

  browser_mode.py show <RUN_DIR> [--cli | --json]
      effective mode: run-config.yaml → browser.headed/slowmo, else SITE_QA_HEADLESS/SITE_QA_SLOWMO, else visible;
      refreshes <RUN_DIR>/playwright-cli.json. --cli: only the options for `playwright-cli -s=<qa-id> open <URL> …`
  browser_mode.py set <RUN_DIR> (--headed | --headless | --default) [--slowmo MS]
      write run-config.yaml → browser, re-export rules.json and <RUN_DIR>/playwright-cli.json: every NEXT start of a
      node script of the skill (they read rules.json) and every next
      `playwright-cli -s=<qa-id> open <URL> --config <RUN_DIR>/playwright-cli.json` use the new mode; no message to the
      executors is needed. Open playwright-cli sessions keep their window until reopened; Playwright MCP is
      configured when it starts (--headless) and does not switch.

  browser_mode.py mcp <RUN_DIR> [--name site-qa-local] [--check] [--json]
      a SEPARATE Playwright MCP server for this run (a local app: Playwright MCP opens file:// only with
      allowUnrestrictedFileAccess, set when it starts): writes <RUN_DIR>/playwright-mcp.json (bundled Chromium,
      in-memory profile, window of the run, allowUnrestrictedFileAccess for site.local_roots, outputDir raw/mcp,
      browser.initPage = <RUN_DIR>/mcp-guard.js — the guard of the run in every tab: file:// only inside local_roots)
      and prints how to add it (claude mcp add … / .mcp.json) — adding a server is the user's decision, nothing is
      changed in Claude Code settings. --check: start that server over stdio and prove it — the start URL opens,
      a file outside local_roots is blocked (node/mcp_check.js). Exit: 0 ok, 1 check failed, 4 no rules.json.

<RUN_DIR>/playwright-cli.json (playwright-cli --config): browser.launchOptions {headless, slowMo} of the run and, for a
local app (site.local_roots), allowUnrestrictedFileAccess: true — playwright-cli blocks file:// without it; the guard
(url_guard.py nav before every goto) stays the boundary.

Order for node scripts (scripts/node/lib.js → browserMode): --headed/--headless of the command > run-config >
environment > visible window (slow-mo 250 ms). references/devices-auth.md → «Окно браузера».
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import runcfg  # noqa: E402
import url_guard  # noqa: E402


CLI_CONFIG = "playwright-cli.json"


def write_cli_config(run_dir, res=None):
    """<RUN_DIR>/playwright-cli.json for `playwright-cli open --config`: window of the run, file:// for local apps."""
    run_dir = Path(run_dir)
    res = res or effective(run_dir)
    cfg = runcfg.load(run_dir / "run-config.yaml")
    try:
        local = bool(url_guard.local_roots_of(cfg))
    except url_guard.GuardUnavailable:
        local = False
    lo = {"headless": not res["headed"]}
    if res["headed"] and res["slowmo"]:
        lo["slowMo"] = res["slowmo"]
    data = {"browser": {"launchOptions": lo}}
    if local:
        data["allowUnrestrictedFileAccess"] = True
    path = run_dir / CLI_CONFIG
    if run_dir.is_dir():
        path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return path


MCP_CONFIG = "playwright-mcp.json"
MCP_GUARD = "mcp-guard.js"


def mcp_files(run_dir, res=None):
    """<RUN_DIR>/playwright-mcp.json + mcp-guard.js for a separate Playwright MCP server of the run -> dict."""
    run_dir = Path(run_dir).resolve()
    res = res or effective(run_dir)
    rules = run_dir / "rules.json"
    if not rules.is_file():
        raise SystemExit(4)
    cfg = runcfg.load(run_dir / "run-config.yaml")
    try:
        roots = url_guard.local_roots_of(cfg)
    except url_guard.GuardUnavailable:
        roots = []
    node_dir = HERE / "node"
    guard_js = run_dir / MCP_GUARD
    guard_js.write_text(
        "// generated by browser_mode.py mcp: the guard of the run in every tab of Playwright MCP (scripts/node/mcp_guard.js)\n"
        f"module.exports.default = require({json.dumps(str(node_dir / 'mcp_guard.js'))})"
        f".make({json.dumps(str(rules))}, {json.dumps(str(run_dir / 'logs' / 'blocked-mcp.jsonl'))});\n", encoding="utf-8")
    lo = {"headless": not res["headed"], "channel": "chromium"}
    if res["headed"] and res["slowmo"]:
        lo["slowMo"] = res["slowmo"]
    data = {"browser": {"browserName": "chromium", "isolated": True, "launchOptions": lo, "initPage": [str(guard_js)]},
            "outputDir": str(run_dir / "raw" / "mcp")}
    if roots:
        data["allowUnrestrictedFileAccess"] = True
    path = run_dir / MCP_CONFIG
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    cli = node_dir / "node_modules" / "playwright" / "cli.js"
    start = next((str(u) for u in (cfg.get("site") or {}).get("start_urls") or []), None)
    return {"config": str(path), "guard": str(guard_js), "local_roots": [r["path"] for r in roots], "start_url": start,
            "command": ["node", str(cli), "mcp", "--config", str(path)], "cli_installed": cli.is_file(), "headed": res["headed"]}


def effective(run_dir):
    cfg = runcfg.load(Path(run_dir) / "run-config.yaml")
    b = url_guard.browser_of(cfg)
    env_h = os.environ.get("SITE_QA_HEADLESS")
    if b["headed"] is not None:
        headed, source = b["headed"], "run-config"
    elif env_h not in (None, ""):
        headed, source = env_h != "1", "env SITE_QA_HEADLESS"
    else:
        headed, source = True, "по умолчанию"
    slowmo = b["slowmo"] if b["slowmo"] is not None else int(os.environ.get("SITE_QA_SLOWMO") or 250)
    return {"headed": headed, "slowmo": slowmo if headed else 0, "source": source, "config": b,
            "playwright_cli": f"--config {Path(run_dir) / CLI_CONFIG}" + (" --headed" if headed else ""),
            "env": f"SITE_QA_HEADLESS={'0' if headed else '1'}" + (f" SITE_QA_SLOWMO={slowmo}" if headed else "")}


def cmd_mcp(a):
    try:
        info = mcp_files(a.run_dir)
    except SystemExit:
        print(f"browser_mode mcp: нет {Path(a.run_dir) / 'rules.json'} — сначала url_guard.py export "
              "--config <RUN_DIR>/run-config.yaml --out <RUN_DIR>/rules.json (без правил MCP не настраивается)", file=sys.stderr)
        sys.exit(4)
    cmd = info["command"]
    info["claude_mcp_add"] = "claude mcp add " + a.name + " -- " + " ".join(json.dumps(x) if " " in x else x for x in cmd)
    info["mcp_json"] = {"mcpServers": {a.name: {"command": cmd[0], "args": cmd[1:]}}}
    code = 0
    if a.check:
        if not info["local_roots"] or not info["start_url"]:
            info["check"] = {"ok": False, "error": "нет site.local_roots / start_urls: проверка file:// не применима"}
            code = 1
        else:
            probe = Path(info["local_roots"][0]).parent / "__site_qa_outside_probe__.html"
            r = subprocess.run(["node", str(HERE / "node" / "mcp_check.js"), "--config", info["config"], "--url", info["start_url"],
                                "--outside", probe.as_uri(), "--log", str(Path(info["config"]).parent / "logs" / "blocked-mcp.jsonl")],
                               capture_output=True, text=True, encoding="utf-8")
            try:
                info["check"] = json.loads(r.stdout)
            except ValueError:
                info["check"] = {"ok": False, "error": (r.stderr or r.stdout).strip()[-400:]}
            code = 0 if info["check"].get("ok") else 1
    if a.json:
        print(json.dumps(info, ensure_ascii=False, indent=1))
        sys.exit(code)
    print(f"Playwright MCP прогона: {info['config']} (guard в каждой вкладке: {info['guard']})")
    print(f"  file:// разрешён только в: {', '.join(info['local_roots']) or '— (сайт без local_roots: file:// закрыт)'}")
    print(f"  окно: {'видно' if info['headed'] else 'скрыто'}; браузер — Chromium скила, профиль в памяти (isolated)")
    print("  Добавить сервер — только по решению пользователя (настройки Claude Code скил не меняет):")
    print(f"    {info['claude_mcp_add']}")
    print(f"    или .mcp.json: {json.dumps(info['mcp_json'], ensure_ascii=False)}")
    print(f"  затем перезапустить сессию; после прогона: claude mcp remove {a.name}")
    print("  Перед каждым browser_navigate — url_guard.py nav (правило §4); guard вкладки — вторая граница.")
    if not info["cli_installed"]:
        print("  ВНИМАНИЕ: нет scripts/node/node_modules/playwright — cd scripts/node && npm install", file=sys.stderr)
    if "check" in info:
        c = info["check"]
        print("  проверка: " + ("OK — старт открылся, файл вне каталога заблокирован" if c.get("ok") else
                                 "НЕ ПРОЙДЕНА — " + json.dumps(c, ensure_ascii=False)[:400]))
    sys.exit(code)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("show", help="текущий режим окна прогона")
    s.add_argument("run_dir")
    g = s.add_mutually_exclusive_group()
    g.add_argument("--cli", action="store_true", help="только флаг для playwright-cli open")
    g.add_argument("--json", action="store_true")
    w = sub.add_parser("set", help="изменить режим окна (run-config.yaml и rules.json)")
    w.add_argument("run_dir")
    m = w.add_mutually_exclusive_group(required=True)
    m.add_argument("--headed", action="store_true", help="окно видно")
    m.add_argument("--headless", action="store_true", help="без окна")
    m.add_argument("--default", action="store_true", help="снять настройку: env или видимое окно")
    w.add_argument("--slowmo", type=int, help="замедление действий в видимом окне, мс")
    p = sub.add_parser("mcp", help="отдельный Playwright MCP прогона (file:// под guard)")
    p.add_argument("run_dir")
    p.add_argument("--name", default="site-qa-local", help="имя MCP-сервера")
    p.add_argument("--check", action="store_true", help="запустить сервер по stdio и проверить: старт открывается, файл вне каталога — нет")
    p.add_argument("--json", action="store_true")
    a = ap.parse_args()
    if a.cmd == "mcp":
        return cmd_mcp(a)
    if a.cmd == "set":
        cfg_path = Path(a.run_dir) / "run-config.yaml"
        old = (runcfg.load(cfg_path).get("browser") or {})
        new = {"headed": True if a.headed else False if a.headless else None,
               "slowmo": a.slowmo if a.slowmo is not None else (old.get("slowmo") if isinstance(old, dict) else None)}
        runcfg.set_top(cfg_path, "browser", new)
        rex = runcfg.reexport_rules(a.run_dir)
        res = effective(a.run_dir)
        write_cli_config(a.run_dir, res)
        print(f"окно браузера: {'видно' if res['headed'] else 'скрыто'}" +
              (f", замедление {res['slowmo']} мс" if res["headed"] else "") + f" (источник: {res['source']})")
        print("  rules.json пересобран — node-скрипты возьмут режим при следующем запуске" if rex and rex["code"] == 0
              else "  rules.json нет — режим попадёт в него при url_guard.py export")
        print(f"  playwright-cli: open <URL> {res['playwright_cli']}; открытые сессии — после переоткрытия своей сессии")
        if rex and rex["code"] != 0:
            print(f"  ОШИБКА export: {rex['output']}", file=sys.stderr)
            sys.exit(4)
        return
    res = effective(a.run_dir)
    write_cli_config(a.run_dir, res)
    if a.cli:
        print(res["playwright_cli"])
    elif a.json:
        print(json.dumps(res, ensure_ascii=False, indent=1))
    else:
        print(f"окно браузера: {'видно' if res['headed'] else 'скрыто'}" +
              (f", замедление {res['slowmo']} мс" if res["headed"] else "") + f" (источник: {res['source']}); "
              f"playwright-cli: open <URL> {res['playwright_cli']}; node-скрипты: из rules.json")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    main()
